/**
 * Relational schema map: camelCase API fields ↔ snake_case DB columns.
 * Source of truth for SQL generation, ETL, and pgDb.
 */

const col = (api, db, type = "text") => ({ api, db, type });
const idRef = (api, db = `${api.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`)}_id`) =>
   col(api, db.endsWith("_id") || db === "id" ? db : `${toSnake(api)}_id`, "text");

function toSnake(s) {
   return s.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`);
}

