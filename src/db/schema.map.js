const sqlType = (type) => {
   switch (type) {
      case "boolean":
         return "BOOLEAN";
      case "numeric":
         return "NUMERIC";
      case "timestamptz":
         return "TIMESTAMPTZ";
      case "jsonb":
         return "JSONB";
      default:
         return "TEXT";
   }
};

const getSchema = (collection) => SCHEMAS[collection];

const allRelationalTables = () => {
   const tables = [];
   for (const [collection, schema] of Object.entries(SCHEMAS)) {
      tables.push({ collection, table: schema.table, kind: "parent" });
      for (const c of schema.children || []) {
         tables.push({ collection, table: c.table, kind: "child", parent: schema.table });
      }
   }
   return tables;
};

